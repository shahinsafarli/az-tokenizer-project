def write(name: str, body: str, sources: list[str]) -> None:
    head = "% AUTO-GENERATED by report/ieee/tables/make_tables.py -- do not edit by hand.\n"
    head += "".join(f"% source: {s}\n" for s in sources)
    # The body ends with \bottomrule so that no table row ends exactly at the end of
    # the \input file (a trailing "\\" at EOF breaks the following \bottomrule).
    (HERE / name).write_text(head + body + "\\bottomrule\n", encoding="utf-8", newline="\n")
    print("wrote", name)


def f4(x) -> str:
    return "--" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.4f}"


def pfmt(p) -> str:
    if p is None or (isinstance(p, float) and np.isnan(p)):
        return "--"
    if p == 0:
        return "$<$1e-5"
    if p < 1e-3:
        return f"{p:.1e}".replace("e-0", "e-")
    return f"{p:.4f}" if p < 1 else "1"


