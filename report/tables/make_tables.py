# ---------------------------------------------------------------- Turkish contrasts, both bases
def contrast(base, n, b, c):
    """stats.csv row for the contrast b -> c, sign-flipped when stored as c -> b."""
    r = stats[(stats.base == base) & (stats.train_size == n) & (stats.baseline == b) & (stats.comparison == c)]
    sign = 1.0
    if not len(r):
        r = stats[(stats.base == base) & (stats.train_size == n) & (stats.baseline == c) & (stats.comparison == b)]
        sign = -1.0
    r = r.iloc[0].copy()
    for col in ("conditional_diff", "all_seed_diff", "paired_mean_diff", "conditional_cohens_d"):
        if not pd.isna(r[col]):
            r[col] = sign * r[col]
    if sign < 0:
        r["baseline_escape"], r["comparison_escape"] = r["comparison_escape"], r["baseline_escape"]
    return r


def paired_test_delta(base, n, b, c):
    """Mean test-F1 difference over seeds escaped in BOTH arms (T2 definition), from run records."""
    A = {r["seed"]: r for r in runs if r["base"] == base and r["train_size"] == n and r["condition"] == b}
    B = {r["seed"]: r for r in runs if r["base"] == base and r["train_size"] == n and r["condition"] == c}
    shared = [s for s in A if A[s]["escaped"] and B[s]["escaped"]]
    if not shared:
        return None, 0
    return float(np.mean([B[s]["test"]["test_macro_f1"] - A[s]["test"]["test_macro_f1"] for s in shared])), len(shared)


